const MARKS: Record<string, (props: { className?: string }) => React.ReactElement> = {
  claude: ClaudeMark,
  codex: CodexMark,
}

export function hasHarnessLogo(harness: string): boolean {
  return harness in MARKS
}

export function HarnessLogo({ harness, className }: { harness: string; className?: string }) {
  const Mark = MARKS[harness]
  if (!Mark) return null
  return <Mark className={cn('h-3.5 w-3.5 shrink-0', className)} />
}
